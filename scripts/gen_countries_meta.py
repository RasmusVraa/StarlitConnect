# -*- coding: utf-8 -*-
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
iso = json.loads((ROOT / 'assets/data/iso3_to_iso2.json').read_text(encoding='utf-8'))
geo = json.loads((ROOT / 'assets/data/countries.geo.json').read_text(encoding='utf-8'))
id_name = {
    str(f.get('id', '')): f['properties'].get('name', '') for f in geo['features']
}
codes = []
seen = set()
for iso3, iso2 in iso.items():
    iso2 = iso2.upper()
    if len(iso2) != 2 or iso2 in seen:
        continue
    name = id_name.get(iso3, '')
    if not name:
        continue
    seen.add(iso2)
    codes.append((iso2, name))
codes.sort()

